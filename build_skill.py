#!/usr/bin/env python3
"""Build or check the self-contained Codex skill from canonical source files."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BUNDLE = Path('.agents/skills/spine-animation')
HEADER = '<!-- Generated by build_skill.py. Edit SKILL.template.md in the repository. -->\n'
UI_METADATA = '''interface:
  display_name: "Spine Animation"
  short_description: "Rig, animate, and preview Spine 4.2 characters"
  default_prompt: "Use $spine-animation to animate my character assets and create a Spine runtime preview."
'''


def generated_files(root: Path) -> dict[Path, bytes]:
    """Return all generated paths and their expected bytes."""
    template = (root / 'SKILL.template.md').read_text(encoding='utf-8')
    if not template.startswith('---\n') or '\n---\n' not in template[4:]:
        raise ValueError('SKILL.template.md must have YAML frontmatter')
    end = template.index('\n---\n', 4) + len('\n---\n')
    skill = (template[:end] + '\n' + HEADER + template[end:]).encode('utf-8')
    files = {
        Path('SKILL.md'): skill,
        BUNDLE / 'SKILL.md': skill,
        BUNDLE / 'agents/openai.yaml': UI_METADATA.encode('utf-8'),
    }
    for directory, pattern in [('scripts', '*.py'), ('references', '*.md')]:
        for source in sorted((root / directory).glob(pattern)):
            files[BUNDLE / directory / source.name] = source.read_bytes()
    for name in ('requirements.txt', 'LICENSE'):
        files[BUNDLE / name] = (root / name).read_bytes()
    return files


def build(root: Path = ROOT, check: bool = False) -> list[Path]:
    """Write generated files, or return stale paths without changing any file."""
    files = generated_files(root)
    stale = []
    for path, data in files.items():
        target = root / path
        if not target.exists() or target.read_bytes() != data:
            stale.append(path)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
    # Remove only obsolete generated tools/references, never user project outputs.
    for directory in ('scripts', 'references'):
        for target in (root / BUNDLE / directory).glob('*'):
            relative = target.relative_to(root)
            if target.is_file() and relative not in files:
                stale.append(relative)
                if not check:
                    target.unlink()
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail on stale generated files')
    args = parser.parse_args()
    stale = build(check=args.check)
    for path in stale:
        print(f'{"Stale" if args.check else "Updated"}: {path}')
    if args.check and stale:
        print('Run python3 build_skill.py and commit the generated files.')
        return 1
    print('Codex skill bundle is current.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
